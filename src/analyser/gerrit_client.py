import base64
import json
import logging

import requests

log = logging.getLogger(__name__)

XSSI_PREFIX = ")]}'"


class GerritClient:
    """Minimal Gerrit REST client. Authenticated endpoints live under /a/."""

    def __init__(self, url: str, user: str, http_password: str, timeout: int = 30):
        self.base = url.rstrip("/")
        self.s = requests.Session()
        self.s.auth = (user, http_password)
        self.timeout = timeout

    @staticmethod
    def _parse(r: requests.Response):
        text = r.text
        if text.startswith(XSSI_PREFIX):
            text = text[len(XSSI_PREFIX):]
        return json.loads(text) if text.strip() else None

    def get_change(self, change: str) -> dict:
        r = self.s.get(
            f"{self.base}/a/changes/{change}",
            params={"o": ["CURRENT_REVISION", "CURRENT_FILES", "DETAILED_ACCOUNTS"]},
            timeout=self.timeout,
        )
        r.raise_for_status()
        return self._parse(r)

    def changed_files(self, change: str, patchset: str) -> list[str]:
        r = self.s.get(f"{self.base}/a/changes/{change}/revisions/{patchset}/files", timeout=self.timeout)
        r.raise_for_status()
        return [f for f in (self._parse(r) or {}) if f != "/COMMIT_MSG"]

    def get_diff_summary(self, change: str, patchset: str, max_files: int = 20) -> str:
        """Patch of the revision (base64 from Gerrit), trimmed for the LLM prompt."""
        r = self.s.get(f"{self.base}/a/changes/{change}/revisions/{patchset}/patch", timeout=self.timeout)
        r.raise_for_status()
        patch = base64.b64decode(r.text).decode("utf-8", errors="replace")
        return patch[:20_000]

    def post_review(self, change: str, patchset: str, message: str) -> None:
        r = self.s.post(
            f"{self.base}/a/changes/{change}/revisions/{patchset}/review",
            json={"message": message, "tag": "autogenerated:jenkins-ai-analyser"},
            timeout=self.timeout,
        )
        r.raise_for_status()
